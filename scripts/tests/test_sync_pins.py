"""Tests for the parsing and emission in scripts/sync-pins.py."""

import importlib.util
import unittest
from pathlib import Path

try:
    import tomllib
except ImportError:
    import tomli as tomllib  # type: ignore[no-redef]

SCRIPTS = Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location("sync_pins", SCRIPTS / "sync-pins.py")
sync = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(sync)

REV_JS = "1" * 40
REV_MD = "2" * 40


def doc(languages, grammars):
    return {"language": languages, "grammar": grammars}


GRAMMARS = [
    {"name": "javascript", "source": {"git": "https://js", "rev": REV_JS}},
    {
        "name": "markdown_inline",
        "source": {"git": "https://md", "rev": REV_MD, "subpath": "tree-sitter-markdown-inline"},
    },
    {"name": "glimmer-javascript", "source": {"git": "https://gjs", "rev": REV_JS}},
    {"name": "local", "source": {"path": "/somewhere"}},
]


def pin_of(language):
    pins = sync.parse_pins(doc([language], GRAMMARS))
    return pins[0] if pins else None


class ParsePins(unittest.TestCase):
    def test_a_language_uses_the_grammar_of_its_own_name(self):
        self.assertEqual(
            pin_of({"name": "javascript"}),
            {
                "name": "javascript",
                "url": "https://js",
                "rev": REV_JS,
                "subpath": "",
                "symbol": "tree_sitter_javascript",
            },
        )

    def test_a_language_naming_another_grammar_gets_that_grammars_source_and_symbol(self):
        pin = pin_of({"name": "jsx", "grammar": "javascript"})
        self.assertEqual((pin["name"], pin["url"], pin["symbol"]), ("jsx", "https://js", "tree_sitter_javascript"))

    def test_the_subpath_is_kept(self):
        pin = pin_of({"name": "markdown.inline", "grammar": "markdown_inline"})
        self.assertEqual(pin["subpath"], "tree-sitter-markdown-inline")

    def test_the_symbol_replaces_dashes_in_the_grammar_name(self):
        self.assertEqual(
            pin_of({"name": "gjs", "grammar": "glimmer-javascript"})["symbol"],
            "tree_sitter_glimmer_javascript",
        )

    def test_a_language_with_no_git_grammar_has_no_pin(self):
        self.assertIsNone(pin_of({"name": "cabal"}))
        self.assertIsNone(pin_of({"name": "local"}))

    def test_pins_are_sorted_by_name(self):
        pins = sync.parse_pins(doc([{"name": "jsx", "grammar": "javascript"}, {"name": "javascript"}], GRAMMARS))
        self.assertEqual([pin["name"] for pin in pins], ["javascript", "jsx"])

    def test_an_abbreviated_rev_is_fatal(self):
        grammars = [{"name": "short", "source": {"git": "https://s", "rev": "abc123"}}]
        with self.assertRaises(SystemExit):
            sync.parse_pins(doc([{"name": "short"}], grammars))

    def test_an_invalid_language_name_is_fatal(self):
        with self.assertRaises(SystemExit):
            sync.parse_pins(doc([{"name": "Java Script", "grammar": "javascript"}], GRAMMARS))


class EmitPins(unittest.TestCase):
    PINS = [
        {
            "name": "markdown.inline",
            "url": "https://md",
            "rev": REV_MD,
            "subpath": "tree-sitter-markdown-inline",
            "symbol": "tree_sitter_markdown_inline",
        }
    ]

    def test_the_file_text(self):
        self.assertEqual(
            sync.emit_pins("a" * 40, self.PINS),
            "# Generated by scripts/sync-pins.py from Helix's languages.toml. Do not hand-edit.\n"
            "\n"
            f'helix-rev = "{"a" * 40}"\n'
            "\n"
            "[[language]]\n"
            'name = "markdown.inline"\n'
            'url = "https://md"\n'
            f'rev = "{REV_MD}"\n'
            'subpath = "tree-sitter-markdown-inline"\n'
            'symbol = "tree_sitter_markdown_inline"\n',
        )

    def test_the_file_parses_back_to_the_pins(self):
        parsed = tomllib.loads(sync.emit_pins("a" * 40, self.PINS))
        self.assertEqual(parsed, {"helix-rev": "a" * 40, "language": self.PINS})


if __name__ == "__main__":
    unittest.main()
