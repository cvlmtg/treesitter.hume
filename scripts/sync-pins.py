#!/usr/bin/env python3
"""Regenerate grammars.toml from helix-editor/helix languages.toml.

Usage: scripts/sync-pins.py [--helix <40-hex commit>]

Reads Helix's languages.toml at `--helix`, or at the `helix-rev` grammars.toml
already holds, and writes one pin per language whose grammar has a git
source: its url, rev, subpath and C symbol. Idempotent: running twice
produces a byte-identical file.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.request
from pathlib import Path
from urllib.error import URLError

try:
    import tomllib
except ImportError:
    try:
        import tomli as tomllib  # type: ignore[no-redef]
    except ImportError:
        sys.exit("error: requires Python 3.11+ or 'pip install tomli'")

GRAMMARS_TOML = Path(__file__).resolve().parent.parent / "grammars.toml"

HEADER = "# Generated by scripts/sync-pins.py from Helix's languages.toml. Do not hand-edit.\n"

# A language name names its archive: lowercase so it stays distinct on
# case-insensitive file systems, no leading dot so it is never a dotfile.
LANGUAGE_NAME = re.compile(r"[a-z0-9_-][a-z0-9._-]*")

FULL_REV = re.compile(r"[0-9a-f]{40}")


def fetch_languages_toml(rev: str) -> dict:
    url = f"https://raw.githubusercontent.com/helix-editor/helix/{rev}/languages.toml"
    print(f"fetching {url}", file=sys.stderr)
    try:
        with urllib.request.urlopen(url, timeout=30) as response:
            return tomllib.loads(response.read().decode())
    except URLError as e:
        sys.exit(f"error: failed to fetch {url}: {e}")


def git_grammars(doc: dict) -> dict[str, dict]:
    """`{name: source}` for each grammar with a git source."""
    grammars = {}
    for entry in doc.get("grammar", []):
        try:
            name = entry["name"]
            source = entry.get("source", {})
            if source.get("git"):
                grammars[name] = {
                    "url": source["git"],
                    "rev": source["rev"],
                    "subpath": source.get("subpath", ""),
                }
        except KeyError as e:
            sys.exit(f"error: malformed grammar entry in languages.toml: missing key {e}")
    return grammars


def parse_pins(doc: dict) -> list[dict]:
    """One pin per language whose grammar has a git source, sorted by name.

    A language uses the grammar of its own name unless it names another, and
    the C symbol comes from the grammar's name, so a language that borrows a
    grammar (`jsx` uses `javascript`) gets that grammar's symbol."""
    grammars = git_grammars(doc)
    pins = []
    for entry in doc.get("language", []):
        try:
            name = entry["name"]
        except KeyError as e:
            sys.exit(f"error: malformed language entry in languages.toml: missing key {e}")
        grammar_name = entry.get("grammar", name)
        grammar = grammars.get(grammar_name)
        if grammar is None:
            print(f"  skip language '{name}': grammar '{grammar_name}' has no git source", file=sys.stderr)
            continue
        if not LANGUAGE_NAME.fullmatch(name):
            sys.exit(f"error: language name '{name}' does not match {LANGUAGE_NAME.pattern}")
        if not FULL_REV.fullmatch(grammar["rev"]):
            sys.exit(f"error: grammar '{grammar_name}' rev '{grammar['rev']}' is not a full commit SHA")
        pins.append(
            {
                "name": name,
                **grammar,
                "symbol": "tree_sitter_" + grammar_name.replace("-", "_"),
            }
        )
    return sorted(pins, key=lambda pin: pin["name"])


def toml_str(value: str) -> str:
    # A JSON string is a valid TOML basic string.
    return json.dumps(value, ensure_ascii=False)


def emit_pins(helix_rev: str, pins: list[dict]) -> str:
    lines = [HEADER, "\n", f"helix-rev = {toml_str(helix_rev)}\n"]
    for pin in pins:
        lines.append("\n[[language]]\n")
        for key in ("name", "url", "rev", "subpath", "symbol"):
            lines.append(f"{key} = {toml_str(pin[key])}\n")
    return "".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--helix", help="the Helix commit to read, a full 40-hex SHA")
    args = parser.parse_args()

    if args.helix:
        helix_rev = args.helix
    else:
        with GRAMMARS_TOML.open("rb") as f:
            helix_rev = tomllib.load(f)["helix-rev"]
    if not FULL_REV.fullmatch(helix_rev):
        sys.exit(f"error: Helix rev '{helix_rev}' is not a full commit SHA")

    pins = parse_pins(fetch_languages_toml(helix_rev))
    tmp = GRAMMARS_TOML.with_suffix(".toml.tmp")
    tmp.write_text(emit_pins(helix_rev, pins), encoding="utf-8")
    os.replace(tmp, GRAMMARS_TOML)
    print(f"wrote {len(pins)} pins to {GRAMMARS_TOML}", file=sys.stderr)


if __name__ == "__main__":
    main()
